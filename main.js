const year = String(new Date().getFullYear());
const stored = localStorage.getItem("portfolio-lang");
const queryLang = new URLSearchParams(location.search).get("lang");
const lang = queryLang === "en" || queryLang === "pt" ? queryLang : stored === "en" ? "en" : "pt";

function apply(next) {
  const t = translations[next];
  document.documentElement.lang = t.htmlLang;
  document.title = t.documentTitle;
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", t.description);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    let value = t[key];
    if (!value) return;
    value = value.replace("{year}", year);
    el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (t[key]) el.setAttribute("aria-label", t[key]);
  });

  const mail = document.getElementById("email-link");
  if (mail) {
    mail.href =
      "mailto:aldoluiz21@gmail.com?subject=" + encodeURIComponent(t.mailSubject);
  }

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.getAttribute("data-set-lang") === next));
  });

  localStorage.setItem("portfolio-lang", next);
}

document.querySelectorAll("[data-set-lang]").forEach((btn) => {
  btn.addEventListener("click", () => apply(btn.getAttribute("data-set-lang")));
});

apply(lang);
